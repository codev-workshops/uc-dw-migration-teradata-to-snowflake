/**********************************************************************
 * DAILY_BALANCE_CHECK — SQL UDTFs (Snowflake)
 * Reimplements the Teradata macro dml/macros/macro_daily_balance_check.sql.
 *
 * The macro returns two result sets, so it becomes two SQL table functions:
 *   1. DAILY_BALANCE_SUMMARY(CHECK_DATE)        — 'BALANCE_SUMMARY'
 *   2. DAILY_NEGATIVE_BALANCE_ALERT(CHECK_DATE) — 'NEGATIVE_BALANCE_ALERT'
 *
 * - :check_date -> CHECK_DATE argument (no default, as in the macro).
 * - (FORMAT ...) -> TO_CHAR(); formatted columns are VARCHAR. A numeric
 *   SORT_AMOUNT column is added so callers can reproduce the macro ORDER BY.
 * - Result set 1: the macro combined QUALIFY ROW_NUMBER() OVER (PARTITION BY
 *   ft.ACCOUNT_KEY ...) with GROUP BY ACCOUNT_TYPE, CURRENCY_CODE, which is
 *   invalid because ACCOUNT_KEY is not grouped. Rewritten to pick the latest
 *   transaction per account first (CTE + QUALIFY), then aggregate.
 * - Result set 2: (ft.RUNNING_BALANCE - a.OVERDRAFT_LIMIT) is formatted as a
 *   whole expression.
 *
 * Usage (was: EXEC BANKING_DW.DAILY_BALANCE_CHECK(CURRENT_DATE);):
 *   SELECT * FROM TABLE(BANKING_DW.DAILY_BALANCE_SUMMARY(CURRENT_DATE()))
 *   ORDER BY ACCOUNT_TYPE, CURRENCY_CODE;
 *   SELECT * FROM TABLE(BANKING_DW.DAILY_NEGATIVE_BALANCE_ALERT(CURRENT_DATE()))
 *   ORDER BY SORT_AMOUNT ASC;
 **********************************************************************/

CREATE OR REPLACE FUNCTION BANKING_DW.DAILY_BALANCE_SUMMARY(CHECK_DATE DATE)
RETURNS TABLE (
    CHECK_TYPE     VARCHAR,
    ACCOUNT_TYPE   VARCHAR,
    CURRENCY_CODE  VARCHAR,
    ACCOUNT_COUNT  NUMBER,
    TOTAL_BALANCE  VARCHAR,
    AVG_BALANCE    VARCHAR,
    MIN_BALANCE    VARCHAR,
    MAX_BALANCE    VARCHAR
)
LANGUAGE SQL
AS
$$
    WITH LATEST_TXN AS (
        SELECT
            a.ACCOUNT_TYPE,
            a.CURRENCY_CODE,
            ft.RUNNING_BALANCE
        FROM BANKING_DW.DIM_ACCOUNT a
        INNER JOIN BANKING_DW.FACT_TRANSACTION ft
            ON a.ACCOUNT_KEY = ft.ACCOUNT_KEY
        WHERE a.CURRENT_FLAG = 'Y'
          AND a.ACCOUNT_STATUS = 'ACTIVE'
          AND ft.TRANSACTION_DATE = CHECK_DATE
        QUALIFY ROW_NUMBER() OVER (PARTITION BY ft.ACCOUNT_KEY
                                   ORDER BY ft.TRANSACTION_TS DESC) = 1
    )
    SELECT
        'BALANCE_SUMMARY' AS CHECK_TYPE,
        ACCOUNT_TYPE,
        CURRENCY_CODE,
        COUNT(*) AS ACCOUNT_COUNT,
        TO_CHAR(SUM(RUNNING_BALANCE), '999,999,999,990.00') AS TOTAL_BALANCE,
        TO_CHAR(AVG(RUNNING_BALANCE), '999,999,990.00') AS AVG_BALANCE,
        TO_CHAR(MIN(RUNNING_BALANCE), '999,999,990.00') AS MIN_BALANCE,
        TO_CHAR(MAX(RUNNING_BALANCE), '999,999,990.00') AS MAX_BALANCE
    FROM LATEST_TXN
    GROUP BY ACCOUNT_TYPE, CURRENCY_CODE
$$;

CREATE OR REPLACE FUNCTION BANKING_DW.DAILY_NEGATIVE_BALANCE_ALERT(CHECK_DATE DATE)
RETURNS TABLE (
    CHECK_TYPE         VARCHAR,
    ACCOUNT_ID         VARCHAR,
    CUSTOMER_NAME      VARCHAR,
    ACCOUNT_TYPE       VARCHAR,
    CURRENT_BALANCE    VARCHAR,
    OVERDRAFT_LIMIT    VARCHAR,
    OVER_LIMIT_AMOUNT  VARCHAR,
    SORT_AMOUNT        NUMBER(15,2)
)
LANGUAGE SQL
AS
$$
    SELECT
        'NEGATIVE_BALANCE_ALERT' AS CHECK_TYPE,
        a.ACCOUNT_ID,
        c.FIRST_NAME || ' ' || c.LAST_NAME AS CUSTOMER_NAME,
        a.ACCOUNT_TYPE,
        TO_CHAR(ft.RUNNING_BALANCE, 'S999,999,990.00') AS CURRENT_BALANCE,
        TO_CHAR(a.OVERDRAFT_LIMIT, '999,999,990.00') AS OVERDRAFT_LIMIT,
        TO_CHAR(ft.RUNNING_BALANCE - a.OVERDRAFT_LIMIT, 'S999,999,990.00') AS OVER_LIMIT_AMOUNT,
        ft.RUNNING_BALANCE AS SORT_AMOUNT
    FROM BANKING_DW.DIM_ACCOUNT a
    INNER JOIN BANKING_DW.DIM_CUSTOMER c
        ON a.CUSTOMER_ID = c.CUSTOMER_ID AND c.CURRENT_FLAG = 'Y'
    INNER JOIN BANKING_DW.FACT_TRANSACTION ft
        ON a.ACCOUNT_KEY = ft.ACCOUNT_KEY
    WHERE a.CURRENT_FLAG = 'Y'
      AND a.ACCOUNT_TYPE NOT IN ('CREDIT_CARD', 'LOAN')
      AND ft.TRANSACTION_DATE = CHECK_DATE
      AND ft.RUNNING_BALANCE < 0
    QUALIFY ROW_NUMBER() OVER (PARTITION BY ft.ACCOUNT_KEY
                               ORDER BY ft.TRANSACTION_TS DESC) = 1
$$;
