/**********************************************************************
 * AML_SCREENING — SQL UDTFs (Snowflake)
 * Reimplements the Teradata macro dml/macros/macro_aml_screening.sql.
 *
 * The macro returns three result sets. A Snowflake stored procedure can
 * return only one result set, so each pattern becomes its own parameterized
 * view (SQL table function) with the macro's parameter defaults:
 *   1. AML_STRUCTURING(...)        — 'STRUCTURING'
 *   2. AML_RAPID_MOVEMENT(...)     — 'RAPID_MOVEMENT'
 *   3. AML_NEW_CUSTOMER_INTL(...)  — 'NEW_CUSTOMER_INTL'
 * Callers run all three (see snowflake/dml/scripts/extract_report.sql).
 *
 * - DEFAULT DATE -> DEFAULT CURRENT_DATE(); other defaults unchanged.
 * - :screening_date - :lookback_days -> DATEADD('day', -LOOKBACK_DAYS, SCREENING_DATE).
 * - date - date -> DATEDIFF('day', ...); date + 3 -> DATEADD('day', 3, ...).
 * - (FORMAT ...) -> TO_CHAR(); formatted columns are VARCHAR. A numeric
 *   SORT_AMOUNT column is added so callers can reproduce the macro ORDER BY.
 *
 * Usage (was: EXEC BANKING_DW.AML_SCREENING(CURRENT_DATE, 30, 50000.00);):
 *   SELECT * FROM TABLE(BANKING_DW.AML_STRUCTURING(CURRENT_DATE(), 30, 50000.00))
 *   ORDER BY SORT_AMOUNT DESC;
 **********************************************************************/

CREATE OR REPLACE FUNCTION BANKING_DW.AML_STRUCTURING(
    SCREENING_DATE   DATE          DEFAULT CURRENT_DATE(),
    LOOKBACK_DAYS    INTEGER       DEFAULT 30,
    AMOUNT_THRESHOLD NUMBER(15,2)  DEFAULT 50000.00
)
RETURNS TABLE (
    PATTERN_TYPE   VARCHAR,
    CUSTOMER_ID    INTEGER,
    CUSTOMER_NAME  VARCHAR,
    KYC_STATUS     VARCHAR,
    ACCOUNT_ID     VARCHAR,
    TXN_COUNT      NUMBER,
    TOTAL_AMOUNT   VARCHAR,
    AVG_AMOUNT     VARCHAR,
    LAST_TXN_DATE  VARCHAR,
    SORT_AMOUNT    NUMBER(18,2)
)
LANGUAGE SQL
AS
$$
    SELECT
        'STRUCTURING' AS PATTERN_TYPE,
        c.CUSTOMER_ID,
        c.FIRST_NAME || ' ' || c.LAST_NAME AS CUSTOMER_NAME,
        c.KYC_STATUS,
        a.ACCOUNT_ID,
        COUNT(*) AS TXN_COUNT,
        TO_CHAR(SUM(ft.BASE_CURRENCY_AMOUNT), '999,999,990.00') AS TOTAL_AMOUNT,
        TO_CHAR(AVG(ft.BASE_CURRENCY_AMOUNT), '999,999,990.00') AS AVG_AMOUNT,
        TO_CHAR(MAX(ft.TRANSACTION_DATE), 'YYYY-MM-DD') AS LAST_TXN_DATE,
        SUM(ft.BASE_CURRENCY_AMOUNT) AS SORT_AMOUNT
    FROM BANKING_DW.FACT_TRANSACTION ft
    INNER JOIN BANKING_DW.DIM_ACCOUNT a
        ON ft.ACCOUNT_KEY = a.ACCOUNT_KEY AND a.CURRENT_FLAG = 'Y'
    INNER JOIN BANKING_DW.DIM_CUSTOMER c
        ON ft.CUSTOMER_KEY = c.CUSTOMER_KEY AND c.CURRENT_FLAG = 'Y'
    WHERE ft.TRANSACTION_DATE BETWEEN DATEADD('day', -LOOKBACK_DAYS, SCREENING_DATE) AND SCREENING_DATE
      AND ft.TRANSACTION_TYPE IN ('CREDIT', 'DEBIT')
      AND ft.BASE_CURRENCY_AMOUNT BETWEEN (AMOUNT_THRESHOLD * 0.8) AND AMOUNT_THRESHOLD
    GROUP BY c.CUSTOMER_ID, c.FIRST_NAME, c.LAST_NAME, c.KYC_STATUS, a.ACCOUNT_ID
    HAVING COUNT(*) >= 3
$$;

CREATE OR REPLACE FUNCTION BANKING_DW.AML_RAPID_MOVEMENT(
    SCREENING_DATE   DATE          DEFAULT CURRENT_DATE(),
    LOOKBACK_DAYS    INTEGER       DEFAULT 30,
    AMOUNT_THRESHOLD NUMBER(15,2)  DEFAULT 50000.00
)
RETURNS TABLE (
    PATTERN_TYPE   VARCHAR,
    CUSTOMER_ID    INTEGER,
    CUSTOMER_NAME  VARCHAR,
    ACCOUNT_ID     VARCHAR,
    CREDIT_DATE    VARCHAR,
    CREDIT_AMOUNT  VARCHAR,
    DEBIT_DATE     VARCHAR,
    DEBIT_AMOUNT   VARCHAR,
    DAYS_BETWEEN   INTEGER,
    SORT_AMOUNT    NUMBER(18,2)
)
LANGUAGE SQL
AS
$$
    SELECT
        'RAPID_MOVEMENT' AS PATTERN_TYPE,
        c.CUSTOMER_ID,
        c.FIRST_NAME || ' ' || c.LAST_NAME AS CUSTOMER_NAME,
        a.ACCOUNT_ID,
        TO_CHAR(cr.CREDIT_DATE, 'YYYY-MM-DD') AS CREDIT_DATE,
        TO_CHAR(cr.CREDIT_AMOUNT, '999,999,990.00') AS CREDIT_AMOUNT,
        TO_CHAR(dr.DEBIT_DATE, 'YYYY-MM-DD') AS DEBIT_DATE,
        TO_CHAR(dr.DEBIT_AMOUNT, '999,999,990.00') AS DEBIT_AMOUNT,
        DATEDIFF('day', cr.CREDIT_DATE, dr.DEBIT_DATE) AS DAYS_BETWEEN,
        cr.CREDIT_AMOUNT AS SORT_AMOUNT
    FROM BANKING_DW.DIM_CUSTOMER c
    INNER JOIN BANKING_DW.DIM_ACCOUNT a
        ON c.CUSTOMER_ID = a.CUSTOMER_ID AND a.CURRENT_FLAG = 'Y'
    INNER JOIN (
        SELECT ACCOUNT_KEY, TRANSACTION_DATE AS CREDIT_DATE,
               BASE_CURRENCY_AMOUNT AS CREDIT_AMOUNT
        FROM BANKING_DW.FACT_TRANSACTION
        WHERE TRANSACTION_TYPE = 'CREDIT'
          AND BASE_CURRENCY_AMOUNT >= AMOUNT_THRESHOLD
          AND TRANSACTION_DATE BETWEEN DATEADD('day', -LOOKBACK_DAYS, SCREENING_DATE) AND SCREENING_DATE
    ) cr ON a.ACCOUNT_KEY = cr.ACCOUNT_KEY
    INNER JOIN (
        SELECT ACCOUNT_KEY, TRANSACTION_DATE AS DEBIT_DATE,
               BASE_CURRENCY_AMOUNT AS DEBIT_AMOUNT
        FROM BANKING_DW.FACT_TRANSACTION
        WHERE TRANSACTION_TYPE IN ('DEBIT', 'TRANSFER')
          AND BASE_CURRENCY_AMOUNT >= AMOUNT_THRESHOLD * 0.9
          AND TRANSACTION_DATE BETWEEN DATEADD('day', -LOOKBACK_DAYS, SCREENING_DATE) AND SCREENING_DATE
    ) dr ON cr.ACCOUNT_KEY = dr.ACCOUNT_KEY
        AND dr.DEBIT_DATE BETWEEN cr.CREDIT_DATE AND DATEADD('day', 3, cr.CREDIT_DATE)
    WHERE c.CURRENT_FLAG = 'Y'
$$;

CREATE OR REPLACE FUNCTION BANKING_DW.AML_NEW_CUSTOMER_INTL(
    SCREENING_DATE   DATE          DEFAULT CURRENT_DATE(),
    LOOKBACK_DAYS    INTEGER       DEFAULT 30,
    AMOUNT_THRESHOLD NUMBER(15,2)  DEFAULT 50000.00
)
RETURNS TABLE (
    PATTERN_TYPE        VARCHAR,
    CUSTOMER_ID         INTEGER,
    CUSTOMER_NAME       VARCHAR,
    ONBOARDING_DATE     VARCHAR,
    DAYS_SINCE_ONBOARD  INTEGER,
    KYC_STATUS          VARCHAR,
    INTL_TXN_COUNT      NUMBER,
    TOTAL_INTL_AMOUNT   VARCHAR,
    SORT_AMOUNT         NUMBER(18,2)
)
LANGUAGE SQL
AS
$$
    SELECT
        'NEW_CUSTOMER_INTL' AS PATTERN_TYPE,
        c.CUSTOMER_ID,
        c.FIRST_NAME || ' ' || c.LAST_NAME AS CUSTOMER_NAME,
        TO_CHAR(c.ONBOARDING_DATE, 'YYYY-MM-DD') AS ONBOARDING_DATE,
        DATEDIFF('day', c.ONBOARDING_DATE, SCREENING_DATE) AS DAYS_SINCE_ONBOARD,
        c.KYC_STATUS,
        COUNT(*) AS INTL_TXN_COUNT,
        TO_CHAR(SUM(ft.BASE_CURRENCY_AMOUNT), '999,999,990.00') AS TOTAL_INTL_AMOUNT,
        SUM(ft.BASE_CURRENCY_AMOUNT) AS SORT_AMOUNT
    FROM BANKING_DW.FACT_TRANSACTION ft
    INNER JOIN BANKING_DW.DIM_CUSTOMER c
        ON ft.CUSTOMER_KEY = c.CUSTOMER_KEY AND c.CURRENT_FLAG = 'Y'
    WHERE ft.IS_INTERNATIONAL = 1
      AND ft.TRANSACTION_DATE BETWEEN DATEADD('day', -LOOKBACK_DAYS, SCREENING_DATE) AND SCREENING_DATE
      AND c.ONBOARDING_DATE >= DATEADD('day', -90, SCREENING_DATE)
    GROUP BY c.CUSTOMER_ID, c.FIRST_NAME, c.LAST_NAME,
             c.ONBOARDING_DATE, c.KYC_STATUS
    HAVING SUM(ft.BASE_CURRENCY_AMOUNT) >= AMOUNT_THRESHOLD
$$;
